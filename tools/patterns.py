"""Aggregate statistics over the replay dataset, from the WINNER's point of view.

The dataset is made of strong players' wins, so we study what the winning side does.
Called by ingest.py; writes knowledge/07_learned_patterns.md.
"""
import collections, os


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "n/a"


def write_patterns(rows, root):
    n = len(rows)
    dec = [r for r in rows if r["winner"] in ("YOU", "OPP")]
    out = ["# Learned patterns: what winning players do (auto-generated by tools/ingest.py, do not edit by hand)\n",
           f"Dataset: **{n} replays**, {len(dec)} with a decided winner. Everything below is from the winner's point of view "
           "unless stated. Small samples are hints; they sharpen as more replays are added.\n"]

    def W(r):
        return [e for e in r["events"] if e["side"] == r["winner"]]

    def L(r):
        return [e for e in r["events"] if e["side"] != r["winner"]]

    out.append("## Game shape\n\n| Metric | Value |\n|---|---|")
    if dec:
        fw = sum(r["first"] == r["winner"] for r in dec)
        out.append(f"| Winner went first | {pct(fw, len(dec))} ({fw}/{len(dec)}) |")
        ts = sorted(r["turns"] for r in dec)
        out.append(f"| Game length (turns) | median {ts[len(ts)//2]}, shortest {ts[0]}, longest {ts[-1]} |")
        fl = [r["lp"][r["winner"]] for r in dec]
        out.append(f"| Winner's LP at the end | average {sum(fl)//len(fl)} (min {min(fl)}, max {max(fl)}) |")
        ob = [sum(e["amount"] for e in L(r) if e["kind"] == "lp_gain") for r in dec]
        out.append(f"| LP the loser gained during the game | average {sum(ob)//len(ob)} |")

    out.append("\n## What winning decks contain (meta)\n")
    main_c = collections.Counter(); copies = collections.defaultdict(list)
    for r in dec:
        for k, v in collections.Counter(r["win_main"]).items():
            main_c[k] += 1; copies[k].append(v)
    out.append(f"Main deck inclusion across {len(dec)} winning decks:\n")
    out.append(", ".join(f"{k} ({v}/{len(dec)}, avg {sum(copies[k])/len(copies[k]):.1f} copies)" for k, v in main_c.most_common(45)) or "none")
    fus = collections.Counter(c for r in dec for c in set(r["win_fusion"]))
    out.append("\n\nFusion decks used: " + (", ".join(f"{k} ({v})" for k, v in fus.most_common(10)) or "none"))
    sd = collections.Counter(c for r in dec for c in set(r["win_sidedeck"]))
    out.append("\n\nSide deck cards used: " + (", ".join(f"{k} ({v})" for k, v in sd.most_common(12)) or "none"))
    out.append("\n\nMain deck sizes: " + ", ".join(str(x) for x in sorted({len(r["win_main"]) for r in dec})))

    out.append("\n## How winners open (their first turn)\n")
    op = collections.Counter(); samples = {}
    for r in dec:
        ft = min((e["turn"] for e in r["events"] if e["kind"] == "turn" and e["side"] == r["winner"]), default=None)
        acts = [(e["kind"], e["card"]) for e in W(r) if e["turn"] == ft and e["kind"] in ("summon", "set_monster", "set_st", "activate")]
        mons = sum(1 for k, _ in acts if k in ("summon", "set_monster"))
        key = (mons, len(acts) - mons)
        op[key] += 1
        samples.setdefault(key, []).append(f"{r['name']}: " + ", ".join(f"{k.replace('_', ' ')} {c}" for k, c in acts))
    for (m, st), c in op.most_common(8):
        out.append(f"- {m} monster(s) and {st} spell/trap card(s) on turn one (x{c}). e.g. {samples[(m, st)][0]}")

    out.append("\n## How games are won\n")
    kill = collections.Counter(); finals = []
    for r in dec:
        la = [e for e in W(r) if e["kind"] in ("attack", "direct")]
        if la:
            kill["direct attack" if la[-1]["kind"] == "direct" else "battle"] += 1
            finals.append(f"{r['name']}: final {la[-1]['kind']} attack with {la[-1].get('attacker')}")
        else:
            kill["effect/other"] += 1
    out.append("Final blow: " + ", ".join(f"{k} x{v}" for k, v in kill.most_common()))
    fc = collections.Counter(f.split("with ")[-1] for f in finals)
    out.append("\nMost frequent final attackers: " + ", ".join(f"{k} x{v}" for k, v in fc.most_common(15)))
    dmg = collections.Counter()
    for r in dec:
        prev = None
        for e in r["events"]:
            if e["kind"] == "lp_loss" and e["side"] != r["winner"] and not e.get("cost"):
                key = prev["kind"] if prev and prev["kind"] in ("attack", "direct") else (f"effect: {prev.get('card')}" if prev else "other")
                dmg[key] += e["amount"]
            elif e["kind"] in ("attack", "direct", "effect", "activate"):
                prev = e
    tot = sum(dmg.values()) or 1
    out.append("\nDamage dealt to losers by source: " + ", ".join(f"{k} {v} ({100 * v // tot}%)" for k, v in dmg.most_common(8)))

    def use(who_win, kinds):
        c = collections.Counter()
        for r in dec:
            for e in (W(r) if who_win else L(r)):
                if e["kind"] in kinds and e.get("card"):
                    c[e["card"]] += 1
        return c

    play = {"summon", "set_monster", "set_st", "activate"}
    out.append("\n## Cards winners play (summon/set/activate)\n")
    out.append(", ".join(f"{k} x{v}" for k, v in use(True, play).most_common(25)) or "none")
    out.append("\n## Cards losers play\n")
    out.append(", ".join(f"{k} x{v}" for k, v in use(False, play).most_common(15)) or "none")
    ef = collections.Counter(e["card"] for r in dec for e in W(r) if e["kind"] == "effect")
    out.append("\n## Effects that fired for winners\n")
    out.append(", ".join(f"{k} x{v}" for k, v in ef.most_common(20)) or "none")

    extra_sections(rows, dec, W, L, out)
    final_turn_section(dec, W, out)
    out.append("")
    open(os.path.join(root, "knowledge", "07_learned_patterns.md"), "w", encoding="utf8").write("\n".join(out) + "\n")


def extra_sections(rows, dec, W, L, out):
    import statistics
    n = len(dec)
    # --- tempo (winners vs losers), averaged
    def cnt(evs, kinds):
        return sum(1 for e in evs if e["kind"] in kinds)
    out.append("\n## Tempo (average per game)\n\n| | Winner | Loser |\n|---|---|---|")
    for label, kinds in (("monster plays", {"summon", "set_monster"}), ("spell/trap plays", {"set_st", "activate"}),
                         ("attacks", {"attack", "direct"}), ("direct attacks", {"direct"}), ("effects fired", {"effect"})):
        w = statistics.mean(cnt(W(r), kinds) for r in dec); l = statistics.mean(cnt(L(r), kinds) for r in dec)
        out.append(f"| {label} | {w:.1f} | {l:.1f} |")

    # --- results by how the game ended, first/second player, length buckets
    out.append("\n## How games end\n")
    ends = collections.Counter(r.get("how", "lp") for r in dec)
    out.append(", ".join(f"{k}: {v} ({pct(v, n)})" for k, v in ends.most_common()))
    out.append("\n\nGame length buckets (turns): " + ", ".join(
        f"{lab} {sum(lo <= r['turns'] <= hi for r in dec)}" for lab, lo, hi in
        (("1-8", 1, 8), ("9-15", 9, 15), ("16-25", 16, 25), ("26-50", 26, 50), ("51+", 51, 999))))
    fast = [r for r in dec if r["turns"] <= 8]
    if fast:
        c = collections.Counter(e["card"] for r in fast for e in W(r) if e["kind"] in ("summon", "set_monster", "set_st", "activate") and e.get("card"))
        out.append("\n\nCards winners play in quick wins (8 turns or fewer): " + ", ".join(f"{k} x{v}" for k, v in c.most_common(15)))

    # --- first-turn behaviour of winners vs losers
    out.append("\n## Turn-one behaviour\n")
    def first_turn(r, side):
        t = min((e["turn"] for e in r["events"] if e["kind"] == "turn" and e["side"] == side), default=None)
        return [e for e in r["events"] if e["turn"] == t and e["side"] == side]
    for lab, who in (("Winners", True), ("Losers", False)):
        mon = []; st = []
        for r in dec:
            side = r["winner"] if who else ("OPP" if r["winner"] == "YOU" else "YOU")
            ev = first_turn(r, side)
            mon.append(cnt(ev, {"summon", "set_monster"})); st.append(cnt(ev, {"set_st", "activate"}))
        out.append(f"- {lab}: on their first turn they play on average {statistics.mean(mon):.2f} monsters and {statistics.mean(st):.2f} spell/trap cards")
    setm = sum(1 for r in dec for e in first_turn(r, r["winner"]) if e["kind"] == "set_monster")
    sumf = sum(1 for r in dec for e in first_turn(r, r["winner"]) if e["kind"] == "summon")
    out.append(f"- Winners' first monster is set face-down {pct(setm, setm + sumf)} of the time ({setm} sets vs {sumf} face-up summons)")
    open_c = collections.Counter(e["card"] for r in dec for e in first_turn(r, r["winner"]) if e["kind"] in ("set_monster", "summon"))
    out.append("- Most common first-turn monsters of winners: " + ", ".join(f"{k} x{v}" for k, v in open_c.most_common(12)))
    open_s = collections.Counter(e["card"] for r in dec for e in first_turn(r, r["winner"]) if e["kind"] in ("set_st", "activate"))
    out.append("- Most common first-turn spell/trap of winners: " + ", ".join(f"{k} x{v}" for k, v in open_s.most_common(12)))

    # --- card lift: inclusion in winning vs losing decks
    out.append("\n## Which cards win: inclusion in winning vs losing decks (lift)\n")
    win_inc = collections.Counter(); lose_inc = collections.Counter()
    for r in dec:
        for c in set(r["win_main"]):
            win_inc[c] += 1
        for c in set(r["lose_main"]):
            lose_inc[c] += 1
    rows_ = []
    for c in set(win_inc) | set(lose_inc):
        a, b = win_inc[c], lose_inc[c]
        if a + b >= 20:
            rows_.append((a / (a + b), a, b, c))
    rows_.sort(reverse=True)
    out.append("Win rate of decks containing the card (min 20 decks; the base rate is 50% by construction, so this shows who shows up in winning lists):\n")
    out.append("| Card | Win-rate | Winning decks | Losing decks |\n|---|---|---|---|")
    for rate, a, b, c in rows_[:20]:
        out.append(f"| {c} | {rate:.0%} | {a} | {b} |")
    out.append("\nLowest:\n\n| Card | Win-rate | Winning decks | Losing decks |\n|---|---|---|---|")
    for rate, a, b, c in rows_[-12:]:
        out.append(f"| {c} | {rate:.0%} | {a} | {b} |")

    # --- deck size
    out.append("\n## Deck size and win rate\n")
    sz = collections.defaultdict(lambda: [0, 0])
    for r in dec:
        sz[len(r["win_main"])][0] += 1
        sz[len(r["lose_main"])][1] += 1
    out.append("| Main deck size | Wins | Losses | Win-rate |\n|---|---|---|---|")
    for k in sorted(sz):
        w, l = sz[k]
        if w + l >= 10:
            out.append(f"| {k} | {w} | {l} | {pct(w, w + l)} |")

    # --- observed copy limits / rule differences
    out.append("\n## Card limits observed in tournament decks\n")
    mx = collections.defaultdict(collections.Counter)
    for r in rows:
        for deck in (r["you_main"], r["opp_main"]):
            for c, v in collections.Counter(deck).items():
                mx[c][v] += 1
    lim1 = sorted(c for c, d in mx.items() if sum(d.values()) >= 15 and max(d) == 1)
    out.append("Never more than 1 copy in 15+ decks (limited): " + ", ".join(lim1))
    var = [(c, dict(sorted(d.items()))) for c, d in mx.items() if sum(d.values()) >= 15 and len(d) > 1 and max(d) >= 2 and sum(v for k, v in d.items() if k > 1) >= 3
           and not (min(d) >= 2)]
    out.append("\n\nCards whose copy count varies (may reveal different rule sets per event): ")
    out.append(", ".join(f"{c} {d}" for c, d in sorted(var)[:40]))
    ver = collections.Counter(r.get("version") for r in rows)
    out.append(f"\n\nReplay file versions seen: {dict(ver)}")
    srcs = collections.Counter(r.get("source") for r in rows)
    out.append(f"\nSources: {dict(srcs)}")


def final_turn_section(dec, W, out):
    import statistics
    out.append("\n## The winning turn\n")
    shapes = collections.Counter(); cards = collections.Counter(); lps = []
    for r in dec:
        ev = r["events"]; w = r["winner"]
        t = [e["turn"] for e in ev if e["kind"] == "turn" and e["side"] == w][-1]
        f = [e for e in ev if e["turn"] == t and e["side"] == w]
        shapes[(sum(e["kind"] == "direct" for e in f), sum(e["kind"] == "attack" for e in f))] += 1
        for e in f:
            if e["kind"] in ("activate", "set_st", "effect") and e.get("card"):
                cards[e["card"]] += 1
        start = [e for e in ev if e["turn"] == t and e["kind"] == "turn"][0]
        lps.append(start["lp_opp"] if w == "YOU" else start["lp_you"])
    out.append("Loser's LP when the winner's last turn begins: median %d, mean %d, 25%% of games below %d" % (
        statistics.median(lps), statistics.mean(lps), sorted(lps)[len(lps) // 4]))
    out.append("\nFinal-turn attack shape (direct attacks, monster attacks): " + ", ".join(
        f"{d} direct + {a} battle x{v}" for (d, a), v in shapes.most_common(8)))
    out.append("\nCards used/fired on the winning turn: " + ", ".join(f"{k} x{v}" for k, v in cards.most_common(20)))
